/**
 * Generates `src/templates/sources.ts` from the repository's `templates/`
 * directory.
 *
 * `templates/` is the project's curated dataset (see PL-5 and catalog.json) and
 * remains the single source of truth for the legal text. The documents are read
 * verbatim and emitted as string constants, so the wording - and the CC BY 4.0
 * attribution line each document carries - cannot drift from the source.
 *
 * Emitting a TypeScript module rather than copying markdown keeps the templates
 * importable from both server and client components without a bundler loader.
 *
 * Runs automatically before `dev` and `build`.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = dirname(dirname(fileURLToPath(import.meta.url)));
const sourceDir = join(dirname(appDir), "templates");
const targetDir = join(appDir, "src", "templates");

const DOCUMENTS = [
  { constant: "coverPageSource", filename: "mutual-nda-coverpage.md" },
  { constant: "standardTermsSource", filename: "mutual-nda.md" },
];

/**
 * The other ten documents, keyed by the id documents.json gives them. They have
 * no cover page of their own - Common Paper publishes one only for the MNDA -
 * so the app generates a key terms page and puts these Standard Terms after it.
 */
const CATALOGUE = join(dirname(appDir), "documents.json");

const parts = [
  "// Generated by scripts/sync-templates.mjs from ../../templates. Do not edit.",
  "// Run `npm run sync-templates` to refresh.",
  "",
];

for (const { constant, filename } of DOCUMENTS) {
  const source = join(sourceDir, filename);

  // Fail loudly rather than building against a stale or missing copy: a silent
  // fallback here would ship a document with the wrong legal text.
  const contents = await readFile(source, "utf8").catch(() => {
    throw new Error(
      `Missing template ${filename} at ${source}. ` +
        `Run this script from the repository checkout so templates/ is present.`,
    );
  });

  if (contents.trim() === "") {
    throw new Error(`Template ${filename} is empty at ${source}.`);
  }

  parts.push(`/** Verbatim contents of templates/${filename}. */`);
  parts.push(`export const ${constant} = ${JSON.stringify(contents)};`);
  parts.push("");
  console.log(`synced ${filename} (${contents.length} bytes)`);
}

const catalogue = JSON.parse(
  await readFile(CATALOGUE, "utf8").catch(() => {
    throw new Error(`Missing ${CATALOGUE}. Run this from the repository checkout.`);
  }),
);

const standardTerms = [];
for (const document of catalogue.documents) {
  const source = join(sourceDir, document.template);

  const contents = await readFile(source, "utf8").catch(() => {
    throw new Error(`Missing template ${document.template} for ${document.id}.`);
  });

  if (contents.trim() === "") {
    throw new Error(`Template ${document.template} is empty at ${source}.`);
  }

  standardTerms.push(`  ${JSON.stringify(document.id)}: ${JSON.stringify(contents)},`);
  console.log(`synced ${document.template} (${contents.length} bytes)`);
}

parts.push("/** Standard Terms for every document but the MNDA, by document id. */");
parts.push("export const standardTermsById: Record<string, string> = {");
parts.push(...standardTerms);
parts.push("};");
parts.push("");

// The catalogue itself, so the form and the key terms page can name and order
// the fields without a network call.
parts.push("/** Verbatim contents of documents.json. */");
parts.push(`export const catalogueSource = ${JSON.stringify(JSON.stringify(catalogue))};`);
parts.push("");

await mkdir(targetDir, { recursive: true });
await writeFile(join(targetDir, "sources.ts"), parts.join("\n"), "utf8");
